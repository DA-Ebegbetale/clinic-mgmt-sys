<?php
declare(strict_types=1);

namespace App\Infrastructure\Export;

use App\Domain\Consultation\Consultation;
use App\Domain\Patient\Patient;
use App\Domain\User\User;
use Dompdf\Dompdf;
use Dompdf\Options;

class DomPdfConsultationExporter
{
    public function export(Consultation $consultation, Patient $patient, User $doctor): void
    {
        // Configure DomPDF
        $options = new Options();
        $options->set('defaultFont', 'Helvetica');
        $options->set('isHtml5ParserEnabled', true);
        $dompdf = new Dompdf($options);

        // Build the HTML Template
        $vitalsHtml = '';
        if ($consultation->getVitals()) {
            foreach ($consultation->getVitals() as $key => $value) {
                $vitalsHtml .= "<li><strong>"
                    . htmlspecialchars(ucfirst($key))
                    . ":</strong> "
                    . htmlspecialchars($value)
                    . "</li>";
            }
        }

        $html = "
        <html>
            <head>
                <style>
                    body { font-family: Helvetica, sans-serif; font-size: 14px; color: #333; line-height: 1.5; }
                    /* Dark Navy Header matching our web Sidebar/Header */
                    .pdf-header { background-color: #1e293b; color: #ffffff; padding: 15px; text-align: center; border-bottom: 4px solid #0056b3; margin-bottom: 20px; }
                    .pdf-header h1 { margin: 0; font-size: 24px; color: #ffffff; }
                    h2 { color: #0056b3; margin-top: 20px; border-bottom: 1px solid #ccc; padding-bottom: 3px; }
                    .header-info { margin-bottom: 20px; padding: 15px; background: #f8f9fa; border-left: 4px solid #0056b3; }
                    .section { margin-bottom: 15px; }
                    .footer-note { position: fixed; bottom: -30px; left: 0; right: 0; text-align: center; font-size: 10px; color: #777; }
                </style>
            </head>
            <body>
                <div class='pdf-header'>
                    <h1>Medical Consultation Report</h1>
                </div>

                <div class='header-info'>
                    <p><strong>Patient:</strong> {$patient->getFirstName()} {$patient->getMiddleName()} {$patient->getLastName()} (DOB: {$patient->getDateOfBirth()})</p>
                    <p><strong>Attending Doctor:</strong> Dr. {$doctor->getFirstName()} {$doctor->getMiddleName()} {$doctor->getLastName()}</p>
                    <p><strong>Visit Date:</strong> {$consultation->getVisitDatetime()}</p>
                    <p><strong>Reference ID:</strong> {$consultation->getUuid()}</p>
                </div>

                <div class='section'>
                    <h2>Chief Complaint</h2>
                    <p>" . nl2br(htmlspecialchars($consultation->getChiefComplaint())) . "</p>
                </div>

                " . ($consultation->getHistoryOfPresentIllness() ? "<div class='section'><h2>History of Present Illness</h2><p>" . nl2br(htmlspecialchars($consultation->getHistoryOfPresentIllness())) . "</p></div>" : "") . "

                " . ($vitalsHtml ? "<div class='section'><h2>Vitals</h2><ul>{$vitalsHtml}</ul></div>" : "") . "

                " . ($consultation->getAssessment() ? "<div class='section'><h2>Assessment</h2><p>" . nl2br(htmlspecialchars($consultation->getAssessment())) . "</p></div>" : "") . "

                " . ($consultation->getDiagnosis() ? "<div class='section'><h2>Diagnosis</h2><p>" . nl2br(htmlspecialchars($consultation->getDiagnosis())) . "</p></div>" : "") . "

                " . ($consultation->getPlan() ? "<div class='section'><h2>Treatment Plan</h2><p>" . nl2br(htmlspecialchars($consultation->getPlan())) . "</p></div>" : "") . "

                " . ($consultation->getPrescription() ? "<div class='section'><h2>Prescription</h2><p>" . nl2br(htmlspecialchars($consultation->getPrescription())) . "</p></div>" : "") . "

                " . ($consultation->getFollowUpDate() ? "<div class='section'><h2>Follow-up Date</h2><p>{$consultation->getFollowUpDate()}</p></div>" : "") . "

                <div class='consultation-footer-note'> 
                    Confidential Medical Record - Electronically signed and verified. <br> generated by {$doctor->getFirstName()} {$doctor->getMiddleName()} {$doctor->getLastName()} on " . date('d M Y, H:i') . ".                
                </div>
            </body>
        </html>";

        // Render and Output
        $dompdf->loadHtml($html);
        $dompdf->setPaper('A4', 'portrait');
        $dompdf->render();

        // Force Download
        $filename = 'Consultation_' . $patient->getLastName() . '_' . date('Y-m-d', strtotime($consultation->getVisitDatetime())) . '.pdf';
        $dompdf->stream($filename, ['Attachment' => true]);
        exit; // Important: Stop PHP execution after sending the file
    }
}